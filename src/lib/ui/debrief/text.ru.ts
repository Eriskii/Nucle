const warheads = (count: number) => {
	if (count === 1) return 'один боезаряд';
	const tens = count % 100;
	const ones = count % 10;
	if (tens >= 11 && tens <= 14) return `${count} боезарядов`;
	if (ones === 1) return `${count} боезаряд`;
	if (ones >= 2 && ones <= 4) return `${count} боезаряда`;
	return `${count} боезарядов`;
};

